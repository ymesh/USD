#!/usr/bin/env bash
# Builds this USD checkout against dependencies from vcpkg (sources already in $VCPKG_ROOT/downloads are reused) and
# installs a self-contained tree to
#     $USD_TOOLS_DIR/USD-v<USD_VER>_rman<RMAN_VER>_py<PY_VER>_vulkan[_clang]
# plus a set_env_usd_<...>.sh next to it. See build_scripts/vcpkg/README.md.
#
# Usage: build_scripts/vcpkg/build.sh [--clang] [--clean] [-j N]
# Environment overrides: VCPKG_ROOT, RMAN_VER (27.3), USD_VENV (/data/code/me/venv3.14), USD_TOOLS_DIR.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
PRESET=linux-gcc
SUFFIX=""
CLEAN=0
JOBS="$(nproc)"
while [ $# -gt 0 ]; do
    case "$1" in
        --clang) PRESET=linux-clang; SUFFIX="_clang" ;;
        --clean) CLEAN=1 ;;
        -j) JOBS="$2"; shift ;;
        -j*) JOBS="${1#-j}" ;;
        -h|--help) sed -n '2,9p' "$0"; exit 0 ;;
        *) echo "[failed] unknown option: $1" >&2; exit 1 ;;
    esac
    shift
done

export VCPKG_ROOT="${VCPKG_ROOT:-/data/code/libs/vcpkg}"
RMAN_VER="${RMAN_VER:-27.3}"
USD_VENV="${USD_VENV:-/data/code/me/venv3.14}"
USD_TOOLS_DIR="${USD_TOOLS_DIR:-/data/tools/USD/pixar}"

[ -x "$VCPKG_ROOT/vcpkg" ] || { echo "[failed] no vcpkg executable in VCPKG_ROOT=$VCPKG_ROOT" >&2; exit 1; }

# --- USD version from cmake/defaults/Version.cmake: 0.26.8 -> 26.08
ver_part() { sed -n "s/^set(PXR_$1_VERSION \"\([0-9]*\)\".*/\1/p" "$ROOT/cmake/defaults/Version.cmake"; }
USD_VER="$(ver_part MINOR).$(printf %02d "$(ver_part PATCH)")"

# --- RenderMan
export RMANTREE="/opt/pixar/RenderManProServer-${RMAN_VER}"
[ -d "$RMANTREE/include" ] || { echo "[failed] RenderMan not found at $RMANTREE" >&2; exit 1; }

# --- Python: the venv's interpreter, linked against its base installation's shared libpython
export USD_PYTHON_EXE="$USD_VENV/bin/python"
[ -x "$USD_PYTHON_EXE" ] || { echo "[failed] no python in $USD_VENV" >&2; exit 1; }
read -r PY_VER PY_LIBDIR PY_LDLIB PY_INC < <("$USD_PYTHON_EXE" -c 'import sys, sysconfig as s
print("%d.%d" % sys.version_info[:2], s.get_config_var("LIBDIR"), s.get_config_var("LDLIBRARY"), s.get_paths()["include"])')
export USD_PYTHON_LIB="$PY_LIBDIR/$PY_LDLIB"
export USD_PYTHON_INCLUDE="$PY_INC"
case "$PY_LDLIB" in
    *.so) ;;
    *) echo "[failed] $USD_PYTHON_EXE has no shared libpython ($PY_LDLIB); rebuild it with --enable-shared" >&2; exit 1 ;;
esac
for m in PySide6 OpenGL jinja2 PyOpenColorIO; do
    "$USD_PYTHON_EXE" -c "import $m" 2>/dev/null || echo "[warning] python module $m missing in $USD_VENV (usdview needs it)" >&2
done

NAME="v${USD_VER}_rman${RMAN_VER}_py${PY_VER}_vulkan${SUFFIX}"
export USD_PREFIX="$USD_TOOLS_DIR/USD-$NAME"
export USD_BUILD_DIR="$USD_TOOLS_DIR/build_$NAME"
TRIPLET="x64-linux-usd${SUFFIX:+-clang}"
LOG="$USD_BUILD_DIR/build.log"

echo "* USD $USD_VER | RenderMan $RMAN_VER | Python $PY_VER | preset $PRESET"
echo "* build:   $USD_BUILD_DIR"
echo "* install: $USD_PREFIX"

if [ "$CLEAN" = 1 ]; then
    rm -rf "$USD_BUILD_DIR/USD"   # keeps vcpkg_installed: finished ports aren't rebuilt
fi
mkdir -p "$USD_BUILD_DIR"

{
    echo "=== $(date '+%F %T') $0 $*"
    # Always configure: quick when nothing changed, and picks up vcpkg.json edits (new ports).
    cmake --preset "$PRESET" -S "$ROOT"
    cmake --build "$USD_BUILD_DIR/USD" -j "$JOBS"
    cmake --install "$USD_BUILD_DIR/USD"
} 2>&1 | tee -a "$LOG"

# --- Make the install self-contained: dependency runtime libraries and MaterialX's standard library.
DEPS="$USD_BUILD_DIR/vcpkg_installed/$TRIPLET"
echo "* copying dependency libraries from $DEPS"
cp -a "$DEPS"/lib/*.so* "$USD_PREFIX/lib/"
for d in "$DEPS/libraries" "$DEPS/share/materialx/libraries"; do
    if [ -d "$d" ]; then
        rm -rf "$USD_PREFIX/libraries"
        cp -a "$d" "$USD_PREFIX/libraries"
        break
    fi
done

# --- Environment script
ENV_SCRIPT="$USD_TOOLS_DIR/set_env_usd_${USD_VER}_rman${RMAN_VER}_py${PY_VER}_vulkan${SUFFIX}.sh"
RMAN_MAJOR="${RMAN_VER%%.*}"
RMAN_MINOR="${RMAN_VER#*.}"
cat > "$ENV_SCRIPT" <<EOF
#
# Setup USD working environment (generated by $ROOT/build_scripts/vcpkg/build.sh)
#
export USD_VER="${USD_VER}"
PY_VER=${PY_VER}

source "${USD_VENV}/bin/activate"
#
# RenderMan
#
source ~/env/rman/env_rman.sh "${RMAN_MAJOR}" "${RMAN_MINOR}"
export LD_LIBRARY_PATH=\${RMANTREE}/lib:\${LD_LIBRARY_PATH}
#
# USD
#
export USD="${USD_PREFIX}"
export USD_LOCATION=\${USD}

export LD_LIBRARY_PATH=\${USD}/lib:\${USD}/plugin/usd:\${LD_LIBRARY_PATH}
export PATH=\${USD}/bin:\${PATH}
export PYTHONPATH=\${USD}/lib/python\${PY_VER}/site-packages:\${PYTHONPATH}
export PXR_MTLX_STDLIB_SEARCH_PATHS=\${USD}/libraries

usd_examples="\${USD}/share/usd/examples/plugin"
export PXR_PLUGINPATH_NAME="\${usd_examples}/usdObj/resources:\${PXR_PLUGINPATH_NAME}"

# Override HdPrman's defaults
export HD_PRMAN_MAX_SAMPLES=128
export USDVIEW_ENABLE_MSAA=1

export USD_EDITOR="usdmanager"
export OCIO="/home/mesh/Documents/OpenColorIO/aces_1.0.3/config.ocio"

echo "* Setup USD v\${USD_VER} working environment."
echo "* USD = \${USD_LOCATION}"
echo "* RMANTREE = \${RMANTREE}"
echo "* PIXAR_LICENSE_FILE = \${PIXAR_LICENSE_FILE}"
echo "* PYTHONPATH = \${PYTHONPATH}"
echo "* OCIO = \${OCIO}"
EOF
echo "* wrote $ENV_SCRIPT"
echo "* done: source $ENV_SCRIPT"
